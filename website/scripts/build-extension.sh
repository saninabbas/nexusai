#!/usr/bin/env bash
set -euo pipefail

project_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
extension_dir="$project_root/extension"
if [[ ! -d "$extension_dir" && -d "$project_root/../extension" ]]; then
  extension_dir="$(cd "$project_root/../extension" && pwd)"
fi
output_directory="$project_root/work"
output_file="$output_directory/Nexus-Trader-Extension.zip"
module_file="$project_root/lib/extension-archive.ts"
temporary_dir="$(mktemp -d)"
trap 'rm -rf "$temporary_dir"' EXIT
temporary_output="$temporary_dir/Nexus-Trader-Extension.zip"

mkdir -p "$output_directory"

files=(
  README.md
  background.js
  binance.js
  config.js
  crypto-utils.js
  dashboard.css
  dashboard.html
  dashboard.js
  manifest.json
  popup.html
  popup.js
  strategies.js
  styles.css
)

for file in "${files[@]}"; do
  test -f "$extension_dir/$file" || { echo "Missing extension file: $file" >&2; exit 1; }
  cp "$extension_dir/$file" "$temporary_dir/$file"
done

node -e 'const fs=require("fs"); const m=JSON.parse(fs.readFileSync(process.argv[1],"utf8")); if(m.manifest_version!==3 || m.version!=="5.1.0" || m.background?.type!=="module") process.exit(1)' "$temporary_dir/manifest.json"

if command -v zip >/dev/null 2>&1; then
  (cd "$temporary_dir" && zip -q -X -9 "$temporary_output" "${files[@]}")
else
  node -e '
    const fs = require("fs");
    const path = require("path");
    const fflate = require("fflate");
    const tempDir = process.argv[1];
    const outputFile = process.argv[2];
    const files = process.argv.slice(3);
    const zipData = {};
    for (const file of files) {
      zipData[file] = fs.readFileSync(path.join(tempDir, file));
    }
    const zipped = fflate.zipSync(zipData, { level: 9 });
    fs.writeFileSync(outputFile, zipped);
  ' "$temporary_dir" "$temporary_output" "${files[@]}"
fi
mv "$temporary_output" "$output_file"
node -e 'const fs=require("fs"); const archive=fs.readFileSync(process.argv[1]); const source=`// Generated by scripts/build-extension.sh. Do not edit manually.\nexport const EXTENSION_ARCHIVE_BASE64 = "${archive.toString("base64")}";\nexport const EXTENSION_ARCHIVE_SIZE = ${archive.length};\n`; fs.writeFileSync(process.argv[2], source);' "$output_file" "$module_file"
echo "Built protected extension archive"
